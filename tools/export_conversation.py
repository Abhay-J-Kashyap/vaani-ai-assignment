"""Copy the raw Claude Code session logs into conversation/ and render a readable transcript from them.

    python -m tools.export_conversation <session.jsonl> [<session.jsonl> ...]

- conversation/<session>.jsonl: the raw log, line for line, with only e-mail addresses replaced by [redacted]
  (Claude Code puts the account e-mail in each session's background context).
- conversation/transcript.md: generated from those files, in time order. Every prompt and every reply in full;
  each tool call on one line; tool output cut to a few lines; Claude Code's injected <system-reminder> blocks
  and the model's hidden reasoning left out. The .jsonl files are the complete record.
"""
import json
import pathlib
import re
import sys

OUT = pathlib.Path("conversation")
EMAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
KEEP = {"noreply@anthropic.com", "git@github.com"}
REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
TOOL_OUT_CHARS = 600


def redact(text: str, locals_: set) -> str:
    """Replace every e-mail address, then any leftover local part of one (e.g. in a search for "name@")."""
    text = EMAIL.sub(lambda m: m.group(0) if m.group(0).lower() in KEEP else "[redacted]", text)
    for local in locals_:
        text = re.sub(re.escape(local), "[redacted]", text, flags=re.I)
    return text


def local_parts(texts) -> set:
    found = set()
    for t in texts:
        for m in EMAIL.finditer(t):
            if m.group(0).lower() not in KEEP and len(m.group(0).split("@")[0]) >= 6:
                found.add(m.group(0).split("@")[0])
    return found


def short(value, n=240) -> str:
    s = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    s = " ".join(s.split())
    return s if len(s) <= n else s[:n] + " …"


def tool_line(block) -> str:
    name, inp = block.get("name", "?"), block.get("input") or {}
    key = next((k for k in ("command", "file_path", "pattern", "query", "description", "prompt", "url") if k in inp), None)
    detail = short(inp[key]) if key else short(inp)
    return f"> 🔧 **{name}**: `{detail.replace('`', 'ʹ')}`"


def result_text(block) -> str:
    c = block.get("content")
    if isinstance(c, list):
        c = "\n".join(p.get("text", "") for p in c if isinstance(p, dict) and p.get("type") == "text")
    c = (c or "").strip()
    if len(c) > TOOL_OUT_CHARS:
        c = c[:TOOL_OUT_CHARS] + f"\n… ({len(c) - TOOL_OUT_CHARS:,} more characters in the raw log)"
    return c


def render(events, out):
    out.write("# Conversation history: The Relay\n\n")
    out.write("Generated by `python -m tools.export_conversation` from the raw Claude Code logs in this folder "
              "(`*.jsonl`), which are the complete, unedited record. Here: every prompt and reply in full, in time "
              "order; tool calls one line each; tool output shortened; Claude Code's injected system reminders and "
              "the model's hidden reasoning omitted. E-mail addresses are replaced by [redacted].\n\n")
    session = None
    for ev in events:
        if ev["session"] != session:
            session = ev["session"]
            out.write(f"\n---\n\n## Session `{session}` (from {ev['ts'][:16].replace('T', ' ')} UTC)\n\n")
        m = ev["message"]
        role, content, ts = m.get("role"), m.get("content"), ev["ts"][:16].replace("T", " ")
        blocks = [{"type": "text", "text": content}] if isinstance(content, str) else (content or [])
        if ev.get("summary"):
            text = content if isinstance(content, str) else "\n".join(b.get("text", "") for b in blocks if b.get("type") == "text")
            out.write(f"### [{ts}] Context summary (written by Claude Code when the context filled up)\n\n"
                      f"<details><summary>Show summary</summary>\n\n{text.strip()}\n\n</details>\n\n")
            continue
        for b in blocks:
            t = b.get("type")
            if role == "user" and t == "text":
                text = REMINDER.sub("", b.get("text", "")).strip()
                if not text or text.startswith("<command-") or text.startswith("<local-command"):
                    continue
                if text.startswith("[Request interrupted"):
                    out.write(f"*{text}*\n\n")
                    continue
                out.write(f"### [{ts}] User\n\n{text}\n\n")
            elif role == "user" and t == "tool_result":
                r = result_text(b)
                if r:
                    fence = "````" if "```" in r else "```"
                    out.write(f"<details><summary>result</summary>\n\n{fence}\n{r}\n{fence}\n\n</details>\n\n")
            elif role == "assistant" and t == "text" and b.get("text", "").strip():
                out.write(f"### [{ts}] Assistant\n\n{b['text'].strip()}\n\n")
            elif role == "assistant" and t == "tool_use":
                out.write(tool_line(b) + "\n\n")


def main(paths):
    OUT.mkdir(exist_ok=True)
    events = []
    raw = {p: p.read_text(encoding="utf-8") for p in map(pathlib.Path, paths)}
    locals_ = local_parts(raw.values())
    for p, text in raw.items():
        lines = text.splitlines()
        red = [redact(line, locals_) for line in lines]
        (OUT / p.name).write_text("\n".join(red) + "\n", encoding="utf-8")
        print(f"{p.name}: {len(lines):,} lines -> {OUT / p.name}")
        for line in red:
            try:
                o = json.loads(line)
            except json.JSONDecodeError:
                continue
            if o.get("type") in ("user", "assistant") and isinstance(o.get("message"), dict) and not o.get("isMeta"):
                events.append({"session": p.stem, "ts": o.get("timestamp", ""), "message": o["message"],
                               "summary": bool(o.get("isCompactSummary"))})
    events.sort(key=lambda e: e["ts"])
    with open(OUT / "transcript.md", "w", encoding="utf-8") as f:
        render(events, f)
    print(f"transcript.md: {len(events):,} messages, {(OUT / 'transcript.md').stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main(sys.argv[1:])
